"""SessionCore implementation; compatibility dependencies are explicit."""

from __future__ import annotations

import asyncio
import os
import shutil
from abc import ABC, abstractmethod
from typing import Any, Awaitable, Callable, Dict, List, Literal, Optional, Tuple

from ....models import (
    AgentType,
    ChatMode,
    ManagedSession,
    StreamCapabilities,
    StreamModelOption,
    StreamModeOption,
)
from ..provider_network import ProviderNetworkError
from .contracts import ProviderGoal, ProviderGoalOrigin, ProviderGoalSnapshot, ProviderRuntime


class SessionCore(ABC):
    """Base contract for a native provider transport.

    Subclasses set :attr:`adapter_id`, :attr:`schema_version`, and the
    capability flags; implement :meth:`_build_command` and
    :meth:`_send_text`; and may override :meth:`start` / :meth:`stop`.
    """

    adapter_id: str = "native"
    schema_version: int = 1
    supports_approval_ui: bool = False
    supports_tool_timeline: bool = False
    supports_images: bool = False
    supports_goals: bool = True
    goal_execution_owner: Optional[Literal["provider_native", "hub_managed"]] = "hub_managed"
    goal_usage_quality: Literal["exact", "estimated", "unavailable"] = "unavailable"
    # Providers with a native system/developer instruction channel consume
    # ``_dot_system_pack`` outside the user prompt.
    supports_native_system_instructions: bool = False
    # One-shot CLIs can leave stdout open after their final Goal response. Other
    # transports own a larger provider run and must emit its terminal event.
    goal_completion_requires_provider_event: bool = False

    def __init__(
        self,
        session: ManagedSession,
        conversation_id_persist: Optional[Callable[[str], None]] = None,
        seed_history: Optional[str] = None,
        on_seed_consumed: Optional[Callable[[], Awaitable[None]]] = None,
    ) -> None:
        self.session = session
        # Optional callback to persist the provider conversation id so a cold
        # restart can resume the same conversation.
        self._conversation_id_persist = conversation_id_persist
        self._process: Optional[asyncio.subprocess.Process] = None
        # One-shot Claude/Cursor processes share a consumer across turns. Tag
        # every queued record (including EOF) with its process generation so a
        # cancelled or lingering reader cannot terminate or contaminate the
        # replacement turn. Codex overrides the output path with its own
        # persistent notification queue.
        self._stdout_queue: asyncio.Queue[tuple[int, Optional[Dict[str, Any]]]] = asyncio.Queue()
        self._stdout_generation = 0
        self._reader_task: Optional[asyncio.Task[None]] = None
        self._stderr_task: Optional[asyncio.Task[None]] = None
        self._stderr_buffer: bytes = b""
        self._started = False
        self._handshake_complete = False
        self._last_error: Optional[str] = None
        # Per-turn exit error: set by ``_drain_oneshot_stdout`` when the one-shot
        # provider subprocess exits nonzero (or before emitting a recognized
        # completion record). Surfaced to the tailer via ``exit_error`` so it
        # can emit an ``error`` event and a failed ``turn_completed``.
        self._exit_error: Optional[str] = None
        self._cwd: str = session.workspace_path or ""
        # Provider conversation id. For a fresh tab this is a constructive
        # placeholder (a UUID generated by the tab manager) that may NOT
        # correspond to an existing provider conversation. We must NOT pass it
        # to ``--resume`` until it has been verified (i.e. the provider has
        # emitted it in a system/init record). Until then we use ``--session-id``
        # (which creates the conversation) or no flag at all.
        #
        # ``_conversation_id_verified`` is seeded from the persisted
        # ``agent_session_id_verified`` flag, never inferred from the mere
        # presence of a UUID. A constructive id that has never been confirmed
        # by the provider must not be treated as resumable.
        self._conversation_id: Optional[str] = session.agent_session_id
        self._conversation_id_verified: bool = bool(
            getattr(session, "agent_session_id_verified", False)
        )
        self._required_conversation_id: Optional[str] = None
        self._delivery_admission: Optional[Callable[[], None]] = None
        # Turn-in-flight guard. A second ``send_message`` while a turn is still
        # generating must raise rather than cancel the active turn (which the
        # old ``_send_lock``-only approach did, because the lock was released
        # the moment ``_spawn_oneshot`` returned).
        self._turn_in_flight: bool = False
        self._turn_completion: Optional[asyncio.Future[None]] = None
        # A provider can expose acceptance before its request response arrives.
        # If that response is lost, completion or confirmed Stop still owns the
        # live turn; generic send failure cleanup must not release its guard.
        self._delivery_uncertain = False
        # Completion can settle execution while the request response reports a
        # contradictory rejection. Runtime input surfaces that response without
        # writing a second terminal edge.
        self._submission_outcome_uncertain = False
        # Set while a client Stop deliberately kills/restarts the persistent
        # provider because its native interrupt could not be confirmed. The EOF
        # of that dying process is expected: the tailer restarts (resuming the
        # thread) instead of failing the session closed. Cleared by ``start``.
        self._client_requested_stop: bool = False
        # Serialize sends so a second prompt never cancels an active turn.
        self._send_lock = asyncio.Lock()
        # Hub Chat runtime guidance is injected once, on the first user turn,
        # to avoid re-paying its tokens on every turn. Only native Chat
        # transports reach this class; Terminal sessions never construct one.
        self._hub_runtime_guidance_injected: bool = False
        # Dot context is prepared at the shared transport boundary so every
        # native provider gets the same memory, rotation, and inbox semantics.
        self._dot_system_pack: str = ""
        self._dot_event_ids: List[str] = []
        self._dot_hidden_system_pack_delivered = False
        self._dot_hidden_system_pack_pending = False
        # Forked-tab history seed: a sentinel-wrapped transcript body prepended
        # once to the first user turn of a fresh provider session so the model
        # actually carries the forked context (a forked tab starts a
        # zero-history provider conversation; provider-native resume cannot
        # truncate to a turn). Populated by ``create_native_session`` from the
        # fork sidecar; ``on_seed_consumed`` deletes that sidecar once injected
        # so a restart cannot seed a second time. See ``agent_stream/fork_seed.py``.
        self._seed_history: Optional[str] = seed_history or None
        self._on_seed_consumed: Optional[Callable[[], Awaitable[None]]] = on_seed_consumed
        self._seed_history_injected: bool = False
        self._current_mode = ChatMode(getattr(session, "chat_mode", ChatMode.DEFAULT)).value
        # Available models, populated by ``prepare_capabilities`` from the
        # runtime-discovered (cursor) or curated static (claude/codex) list.
        self._available_models: List[StreamModelOption] = []
        # Claude prepares a settings file and matching process environment as
        # one unit before calling the shared one-shot launcher.
        self._prepared_provider_env: Optional[Dict[str, str]] = None

    @abstractmethod
    def _build_command(self) -> List[str]:
        """Return the argv used to launch the provider in streaming mode."""

    def _begin_turn(self) -> None:
        """Mark a turn as in flight.

        Raises ``RuntimeError`` if a turn is already active. The caller must
        hold ``_send_lock``.
        """
        if self._turn_in_flight:
            raise RuntimeError(
                "a turn is already in flight; wait for it to complete before "
                "sending another message"
            )
        self._turn_in_flight = True
        loop = asyncio.get_running_loop()
        self._turn_completion = loop.create_future()

    def _end_turn(self) -> None:
        """Mark the active turn as complete and resolve its completion future."""
        self._turn_in_flight = False
        fut = self._turn_completion
        self._turn_completion = None
        if fut is not None and not fut.done():
            fut.set_result(None)

    def acknowledge_turn_complete(self) -> None:
        """Acknowledge that the tailer has consumed the turn-end signal.

        The tailer calls this after it has processed the provider's terminal
        ``TURN_COMPLETED`` event (the ``result`` record for Claude,
        ``turn_ended`` for Cursor, ``turn/completed`` for Codex) and released
        the active turn id. Only then is ``_turn_in_flight`` cleared, so a
        concurrent ``send_message`` can never overwrite ``_active_turn_id``
        while the previous turn's records are still queued.

        Releasing at ``TURN_COMPLETED`` (rather than waiting for the one-shot
        subprocess to exit) is safe because every adapter emits
        ``TURN_COMPLETED`` as its final record — there are no trailing records
        after it. It also prevents the turn guard from staying stuck while a
        long-running tool call (e.g. ``pnpm dev``) keeps the subprocess alive
        after the turn has logically completed.

        This is the normal-completion counterpart to ``_end_turn`` (which is
        reserved for error/shutdown paths where no turn-end record arrives).
        """
        # For one-shot providers, a completed process may remain alive briefly
        # after its final result (for example while a child tool process keeps
        # stdout open). Retire that stream before releasing the turn guard so
        # its later records/EOF cannot be attributed to the next turn.
        if not self.eof_is_fatal:
            self._invalidate_stdout_stream()
        self._end_turn()

    def acknowledge_provider_turn_started(self) -> None:
        """Acquire the guard for a provider-initiated turn."""
        if not self._turn_in_flight:
            self._begin_turn()

    @property
    def turn_in_flight(self) -> bool:
        return self._turn_in_flight

    async def cancel_active_turn(self) -> None:
        """Abort the in-flight turn and release the turn guard.

        One-shot providers terminate the active subprocess. Persistent
        providers (Codex) attempt a provider-native cancel RPC when available.
        """
        if not self._turn_in_flight:
            return
        # ``_terminate_process`` retires the active one-shot reader first, so
        # the EOF its cancellation publishes is already stale by the time a
        # consumer in ``read_line`` can observe it.
        await self._terminate_process()
        self._clear_staged_images()
        self._end_turn()

    def available_modes(self) -> List[StreamModeOption]:
        return [self._runtime.default_mode()]

    def current_model(self) -> Optional[str]:
        """Return the provider's effective model when it is known."""

        return None

    def current_reasoning_effort(self) -> Optional[str]:
        """Return the effective reasoning effort when it is known."""

        return None

    async def prepare_capabilities(self) -> None:
        """Discover the available models for this session's agent type.

        Claude uses the model ids configured for this specific session, with
        the curated list only as a fallback. Cursor is probed at runtime via
        ``agent --list-models``; other agent types use the curated static list.
        Shared results are cached with a TTL (see ``available_models_for``), so
        this is cheap to call on every capabilities fetch.
        """
        if self.session.agent_type == AgentType.CLAUDE:
            configured = self._runtime.claude_env_options(self.session.env)
            if configured:
                self._available_models = configured
                return
        self._available_models = await self._runtime.available_models_for(
            self.session.agent_type.value
        )

    async def set_mode(self, mode: str) -> None:
        """Select the mode used by the next turn and reject unsafe changes."""

        if self.turn_in_flight:
            raise RuntimeError("cannot change Chat mode while a turn is in flight")
        await self.prepare_capabilities()
        available = {item.id for item in self.available_modes()}
        if mode not in available:
            raise ValueError(f"unsupported Chat mode for {self.session.agent_type.value}: {mode}")
        self._current_mode = mode
        self.session.chat_mode = ChatMode(mode)

    def update_env(self, env: Dict[str, str]) -> None:
        """Replace the session env used for the next turn.

        Claude/Cursor rebuild their command every turn, so the new env is
        picked up live. Codex is a persistent app-server whose model is fixed
        at thread start; its ``CODEX_MODEL`` selection is instead injected
        per-turn via ``collaborationMode.settings.model`` (see
        ``_selected_model_override``), so it likewise takes effect on the
        next ``send_message`` without restarting the app-server.
        """
        self.session.env = dict(env)

    @property
    def eof_is_fatal(self) -> bool:
        """Whether an EOF on the transport's stdout is a fatal error.

        For one-shot providers (Claude/Cursor) EOF means the turn completed
        normally; the push consumer should keep waiting for the next turn.
        For persistent providers (Codex app-server) EOF means the server
        died and the session must fail closed.
        """
        return False

    def require_resumed_conversation(
        self,
        conversation_id: Optional[str],
        *,
        before_delivery: Optional[Callable[[], None]] = None,
    ) -> None:
        """Fence automatic continuation against a fresh-conversation fallback."""
        if conversation_id is not None and (
            not self._conversation_id_verified or self._conversation_id != conversation_id
        ):
            raise RuntimeError("the original provider conversation is no longer available")
        self._required_conversation_id = conversation_id
        self._delivery_admission = before_delivery

    def check_resumed_conversation(self) -> None:
        expected = self._required_conversation_id
        if expected is not None and (
            not self._conversation_id_verified
            or self._conversation_id != expected
            or (self.active_thread_id is not None and self.active_thread_id != expected)
        ):
            raise RuntimeError("the original provider conversation could not be resumed")

    def check_delivery_admission(self) -> None:
        """Recheck automatic intent after preparation, at the input boundary."""
        self.check_resumed_conversation()
        if self._delivery_admission is not None:
            self._delivery_admission()

    async def _prepare_for_send(self) -> None:
        """Apply provider lifecycle changes before accepting the next turn."""

    async def send_message(self, text: str, images: List[bytes]) -> None:
        """Atomically deliver a user turn (text + images) to the provider.

        This is the single input entry point for the composer. It acquires the
        send lock once, checks the turn-in-flight guard, stages images, and
        sends the text prompt. If any step fails, staged images are cleared
        and the turn guard is released so they cannot leak into a later turn.

        Subclasses implement :meth:`_send_text` and :meth:`_stage_images`
        (both lock-free); this method owns the lock and the turn guard.
        """
        async with self._send_lock:
            await self._prepare_for_send()
            self.check_delivery_admission()
            self._delivery_uncertain = False
            self._submission_outcome_uncertain = False
            self._begin_turn()
            try:
                if images:
                    self._stage_images(images)
                try:
                    prompt, seed_included = await self._with_first_turn_prefixes(text)
                except asyncio.CancelledError:
                    self._clear_staged_images()
                    self._end_turn()
                    raise
                await self._send_text(prompt)
                await self._on_turn_sent()
                # The provider accepted the turn; commit the one-shot fork
                # seed ONLY when this turn actually carried it. An image-only
                # first turn carries no prompt text and therefore no seed; it
                # must defer both seed and sidecar deletion to the first text
                # turn rather than silently dropping the forked context.
                if seed_included:
                    await self._mark_seed_delivered()
            except Exception:
                if not (self._delivery_uncertain or self._submission_outcome_uncertain):
                    self._clear_staged_images()
                    self._end_turn()
                raise

    async def _with_first_turn_prefixes(self, text: str) -> Tuple[str, bool]:
        """Composes the first turn's prompt with its one-shot prefix blocks.

        Returns ``(prompt, seed_included)`` where ``seed_included`` is True only
        when the forked-history seed block was actually prepended on this turn.
        The caller commits the seed (and deletes its sidecar) solely when this
        is True, so an image-only first turn defers the seed to the first text
        turn instead of marking it delivered without ever sending it.
        """
        turn_context = await self._prepare_turn_context(text)
        prefix = ""
        seed_included = False
        if text and self._seed_history and not self._seed_history_injected:
            prefix = self._runtime.wrap_fork_seed_history(self._seed_history)
            seed_included = True
        if not text and not turn_context:
            return text, False
        if not self._hub_runtime_guidance_injected:
            self._hub_runtime_guidance_injected = True
            text = self._runtime.wrap_runtime_guidance()(text, context=turn_context)
        elif turn_context:
            text = self._runtime.wrap_runtime_guidance()(text, guidance=None, context=turn_context)
        return prefix + text, seed_included

    async def _prepare_turn_context(self, text: str) -> str:
        """Prepares provider-neutral Dot context and conversation rotation."""
        self._dot_event_ids = []
        self._dot_hidden_system_pack_pending = False
        from ...dot import get_dot_service

        service = get_dot_service()
        raw_tab_id = getattr(self.session, "tab_id", None)
        if not service.is_dot_tab(raw_tab_id):
            return ""
        tab_id = str(raw_tab_id)
        prepare_task = asyncio.create_task(
            asyncio.to_thread(service.prepare_turn, text, self._conversation_id)
        )
        cancellation: Optional[asyncio.CancelledError] = None
        while not prepare_task.done():
            try:
                await asyncio.shield(prepare_task)
            except asyncio.CancelledError as exc:
                cancellation = cancellation or exc
                continue
            except Exception:
                break
        try:
            plan = prepare_task.result()
        except Exception:
            self._runtime.logger().exception(
                "Dot context preparation failed; sending the turn without it"
            )
            if cancellation is not None:
                raise cancellation
            return ""
        if cancellation is not None:
            try:
                service.request_rotation(
                    prepared_generation=plan.prepared_generation,
                    tab_id=tab_id,
                )
            except Exception:
                self._runtime.logger().exception(
                    "Dot context preparation cancellation retry marker failed"
                )
            raise cancellation
        if plan.rotate:
            try:
                conversation_id = await self.rotate_conversation()
            except BaseException:
                service.request_rotation(
                    prepared_generation=plan.prepared_generation, tab_id=tab_id
                )
                raise
            try:
                associated = service.associate_conversation(
                    conversation_id,
                    prepared_generation=plan.prepared_generation,
                    tab_id=tab_id,
                )
            except BaseException:
                service.clear_conversation_association(
                    conversation_id,
                    prepared_generation=plan.prepared_generation,
                    tab_id=tab_id,
                )
                await self._discard_rotation(conversation_id)
                service.request_rotation(
                    prepared_generation=plan.prepared_generation, tab_id=tab_id
                )
                raise
            if not associated:
                await self._discard_rotation(conversation_id)
                service.request_rotation(
                    prepared_generation=plan.prepared_generation, tab_id=tab_id
                )
                raise RuntimeError("Dot provider rotation no longer belongs to the current session")
            try:
                self.adopt_rotated_conversation(conversation_id)
            except BaseException:
                service.clear_conversation_association(
                    conversation_id,
                    prepared_generation=plan.prepared_generation,
                    tab_id=tab_id,
                )
                await self._discard_rotation(conversation_id)
                service.request_rotation(
                    prepared_generation=plan.prepared_generation, tab_id=tab_id
                )
                raise
            self._hub_runtime_guidance_injected = False
            self._dot_hidden_system_pack_delivered = False
        elif plan.new_session:
            self._dot_hidden_system_pack_delivered = False
        self._dot_system_pack = plan.system_pack
        self._dot_event_ids = plan.delivered_event_ids
        return self._dot_prompt_context(plan.turn_pack)

    def _dot_prompt_context(self, turn_pack: str) -> str:
        if self.supports_native_system_instructions or self._dot_hidden_system_pack_delivered:
            return turn_pack
        self._dot_hidden_system_pack_pending = bool(self._dot_system_pack)
        return "\n\n".join(part for part in (self._dot_system_pack, turn_pack) if part)

    async def _on_turn_sent(self) -> None:
        """Acknowledges Dot context only after the provider accepted the turn."""
        if self._dot_hidden_system_pack_pending:
            self._dot_hidden_system_pack_delivered = True
            self._dot_hidden_system_pack_pending = False
        event_ids, self._dot_event_ids = self._dot_event_ids, []
        if not event_ids:
            return
        from ...dot import get_dot_service

        try:
            await asyncio.to_thread(get_dot_service().mark_delivered, event_ids)
        except Exception:
            self._runtime.logger().exception("Dot inbox ack failed")

    async def rotate_conversation(self) -> str:
        """Prepares a fresh provider conversation without adopting its identity."""
        raise NotImplementedError(f"{self.adapter_id} does not support conversation rotation")

    def adopt_rotated_conversation(self, conversation_id: str) -> None:
        """Makes a guarded constructive rotation the active conversation."""
        self._conversation_id = conversation_id
        self._conversation_id_verified = False

    async def discard_rotated_conversation(self, conversation_id: str) -> None:
        """Releases a candidate rejected before its identity was adopted."""

    async def _discard_rotation(self, conversation_id: str) -> None:
        task = asyncio.create_task(self.discard_rotated_conversation(conversation_id))
        cancellation: Optional[asyncio.CancelledError] = None
        while not task.done():
            try:
                await asyncio.shield(task)
            except asyncio.CancelledError as exc:
                cancellation = cancellation or exc
                continue
            except Exception:
                break
        try:
            await task
        except Exception:
            self._runtime.logger().exception(
                "failed to discard rejected %s conversation rotation %s",
                self.adapter_id,
                conversation_id,
            )
        if cancellation is not None:
            raise cancellation

    async def _mark_seed_delivered(self) -> None:
        """Record a successful first-turn seed delivery and drop its sidecar.

        Called only after the provider accepted the seeded turn. Clears the
        in-memory seed so later turns are bare and invokes the at-most-once
        callback that deletes the durable fork sidecar. A callback failure is
        logged but not retried here: the in-memory flag already guarantees the
        seed is sent once per session; the sidecar is only a cross-restart
        handoff.
        """
        if self._seed_history_injected or not self._seed_history:
            return
        self._seed_history_injected = True
        callback = self._on_seed_consumed
        self._seed_history = None
        self._on_seed_consumed = None
        if callback is not None:
            try:
                await callback()
            except Exception:
                self._runtime.logger().warning("fork-seed consumed callback failed", exc_info=True)

    async def answer_pending_question(
        self,
        answers: List[Dict[str, Any]],
        *,
        expected_call_id: Optional[str] = None,
    ) -> bool:
        """Answer a provider-native blocking question, if one is pending.

        Some providers (Codex) block the in-flight turn on a server→client
        question request. The composer's structured answer is routed here
        *before* the normal turn guard, so it is delivered as the question's
        JSON-RPC response rather than as a new (turn-cancelling) steer.

        Returns ``True`` when the transport consumed the answers (a question
        was pending), ``False`` to let the caller fall through to normal
        delivery. The base implementation has no question channel.
        """
        return False

    def accepts_notification(self, record: Dict[str, Any]) -> bool:
        """Whether a dequeued record still belongs to a live provider turn."""
        return True

    @abstractmethod
    async def _send_text(self, text: str) -> None:
        """Provider-specific turn submission (lock-free).

        The caller holds ``_send_lock`` and has already called ``_begin_turn``.
        This method must consume any staged images (clearing ``_staged_images``
        or moving them to ``_inflight_images``) so a successful turn does not
        leak attachments.
        """

    def _stage_images(self, images: List[bytes]) -> None:
        """Stage image bytes for the next turn (lock-free).

        The base implementation raises ``NotImplementedError``; subclasses
        that support images override this to validate and store the bytes.
        """
        if not self.supports_images:
            raise NotImplementedError(f"{self.adapter_id} does not support image input")

    def _clear_staged_images(self) -> None:
        """Discard any staged images (lock-free).

        Called on send failure so attachments never leak across turns.
        Subclasses that stage to temp files override this to delete them.
        """

    async def goal_snapshot(self) -> Optional[ProviderGoalSnapshot]:
        """Return native Goal state; None means this provider has no native API."""
        return None

    async def goal_set(self, goal: ProviderGoal, *, origin: ProviderGoalOrigin) -> ProviderGoal:
        """Mutate a provider-owned Goal without starting a Hub-managed turn."""
        raise NotImplementedError(f"{self.adapter_id} does not support native Goals")

    async def goal_clear(self, *, origin: ProviderGoalOrigin) -> bool:
        """Clear a native Goal; False denotes an already absent supported Goal."""
        raise NotImplementedError(f"{self.adapter_id} does not support native Goals")

    def capabilities(self) -> StreamCapabilities:
        # For CHAT sessions the native transport is the sole real-time source.
        # ``structured`` is True only when (a) the provider binary is
        # discoverable on PATH and (b) the transport has not recorded a fatal
        # error. We must not depend on ``_handshake_complete``, which stays
        # False for one-shot transports (Claude/Cursor) until the first turn
        # produces a system/init record — but the transport *can* deliver
        # structured events as soon as the binary exists.
        binary = self._build_command()[0]
        binary_available = shutil.which(binary) is not None
        if not binary_available:
            self._last_error = f"provider binary not found on PATH: {binary}"
        available_modes = self.available_modes()
        mode_supported = self._current_mode in {item.id for item in available_modes}
        return StreamCapabilities(
            structured=binary_available and self._last_error is None and mode_supported,
            adapter_id=self.adapter_id,
            schema_version=self.schema_version,
            sources=[],
            supports_approval_ui=self.supports_approval_ui,
            supports_tool_timeline=self.supports_tool_timeline,
            supports_images=self.supports_images,
            available_modes=available_modes,
            current_mode=self._current_mode,
            supports_dynamic_modes=len(available_modes) > 1,
            available_models=self._available_models,
            supports_goals=self.supports_goals,
            goal_execution_owner=self.goal_execution_owner,
            goal_usage_quality=self.goal_usage_quality,
            current_model=self.current_model(),
            current_reasoning_effort=self.current_reasoning_effort(),
        )

    @property
    def last_error(self) -> Optional[str]:
        return self._last_error

    @property
    def exit_error(self) -> Optional[str]:
        """Per-turn exit error from a nonzero provider subprocess exit.

        ``None`` when the last turn exited cleanly (or no turn has run yet).
        Set by ``_drain_oneshot_stdout`` after the process exits; consumed by the
        tailer's EOF handler to decide whether to emit a failed
        ``turn_completed``.
        """
        return self._exit_error

    def _build_env(self) -> Dict[str, str]:
        """Merge the inherited environment with session.env overrides.

        PATH is always preserved from the parent environment so the provider
        binary and its toolchain remain discoverable.

        ``CLAUDE_HUB_TAB_ID`` is overlaid here for every native Chat provider
        subprocess. The tab id otherwise reaches only the tmux-shell path
        (``TTYDProcess._child_env``); a native Chat transport spawns the
        provider directly with this env, so without this overlay Cursor /
        Codex / TraeX (which, unlike Claude, have no ``--settings`` carrier)
        would start without the id the Hub-runtime guidance points at, and
        ``$CLAUDE_HUB_TAB_ID`` would expand empty in a self-scheduled command.
        ``setdefault`` keeps an explicit value (from the parent env or
        ``session.env``) authoritative. This is process env only — it is never
        written back to the persisted tab env.
        """
        # Apply deployment defaults before explicit session overrides;
        # normalize each layer so single-case proxy overrides replace both.
        env = self._runtime.provider_subprocess_env(
            self.session.agent_type.value, os.environ, self.session.env
        )
        tab_id = getattr(self.session, "tab_id", None)
        if tab_id:
            env.setdefault("CLAUDE_HUB_TAB_ID", tab_id)
        # Never let the session override PATH away; keep the inherited PATH.
        if "PATH" not in env:
            env["PATH"] = os.environ.get("PATH", "")
        return env

    def _provider_configuration_env(self) -> Dict[str, str]:
        """Return the effective provider configuration visible at launch."""
        return self._build_env()

    async def _build_provider_env(self) -> Dict[str, str]:
        """Select direct or proxied networking for the next subprocess."""
        try:
            selected = await self._runtime.select_provider_env(
                self.session.agent_type.value,
                self._provider_configuration_env(),
            )
        except ProviderNetworkError as exc:
            self._last_error = str(exc)
            raise
        self._last_error = None
        return selected

    def _provider_network_fingerprint(self) -> str:
        return self._runtime.network_fingerprint(
            self.session.agent_type.value,
            self._provider_configuration_env(),
        )

    def _resume_arg(self) -> List[str]:
        """Return the session-id argument for the next turn.

        Base behavior: only pass ``--resume`` when the conversation id has
        been verified (the provider emitted it in a system/init record). For
        an unverified constructive id, pass nothing — subclasses override to
        use a provider-specific constructive flag (Claude: ``--session-id``;
        Cursor: ``--resume`` is itself constructive).
        """
        sid = self._conversation_id
        if sid and self._conversation_id_verified:
            return ["--resume", sid]
        return []

    def _persist_conversation_id(self, cid: str) -> None:
        """Capture and persist the provider conversation id for resume."""
        if not cid:
            return
        if cid == self._conversation_id and self._conversation_id_verified:
            return
        self._conversation_id = cid
        self._conversation_id_verified = True
        if self._conversation_id_persist is not None:
            try:
                self._conversation_id_persist(cid)
            except Exception:
                self._runtime.logger().exception("failed to persist conversation id %s", cid)

    def _adopt_rotated_conversation_id(self, conversation_id: str) -> None:
        """Persists a provider-assigned rotation before adopting it locally."""
        previous = self._conversation_id
        if self._conversation_id_persist is not None:
            try:
                self._conversation_id_persist(conversation_id)
            except BaseException:
                if previous:
                    try:
                        self._conversation_id_persist(previous)
                    except Exception:
                        self._runtime.logger().exception(
                            "failed to restore conversation id %s after rotation persistence failed",
                            previous,
                        )
                raise
        self._conversation_id = conversation_id
        self._conversation_id_verified = True

    def maybe_capture_conversation_id(self, record: Dict[str, Any]) -> None:
        """Provider-specific hook to extract the conversation id from a record.

        The base implementation is a no-op. Claude/Cursor override to capture
        the id from ``message_start``; Codex captures it during thread/start.
        """

    @property
    def active_thread_id(self) -> Optional[str]:
        """Provider-native id of the thread the active user turn runs in.

        Codex/TraeX hold the verified ``thread/start`` id in ``_thread_id``
        (mirrored into ``_conversation_id``). The stream adapter compares each
        item's ``threadId`` against this to tell the main agent apart from a
        nested sub-agent thread. One-shot providers (Claude/Cursor) have no
        persistent thread and return ``None``, which makes the adapter fall
        back to main-stream attribution for everything."""
        thread_id = getattr(self, "_thread_id", None)
        if isinstance(thread_id, str) and thread_id:
            return thread_id
        if self._conversation_id and self._conversation_id_verified:
            return self._conversation_id
        return None

    @property
    @abstractmethod
    def _runtime(self) -> ProviderRuntime:
        """Return the immutable dependency bundle supplied by the concrete owner."""

    @abstractmethod
    async def start(self) -> None: ...

    @abstractmethod
    async def stop(self) -> None: ...

    @abstractmethod
    def _invalidate_stdout_stream(self) -> None: ...

    @abstractmethod
    async def _terminate_process(self) -> None: ...
